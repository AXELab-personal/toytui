bool isZeroWidthCodePoint(char32_t cp) {
    if (cp < 0x0300) {
        return false;
    }
    const auto it = std::upper_bound(std::begin(kZero), std::end(kZero), cp,
                                     [](char32_t c, const Range& r) { return c < r.lo; });
    return it != std::begin(kZero) && cp <= std::prev(it)->hi;
}

char32_t decodeCodePoint(std::string_view s) {
    if (s.empty()) {
        return 0;
    }
    const auto b = [&](std::size_t i) { return static_cast<char32_t>(static_cast<unsigned char>(s[i])); };
    if (b(0) < 0x80 || s.size() == 1) {
        return b(0);
    }
    if (s.size() == 2) {
        return ((b(0) & 0x1F) << 6) | (b(1) & 0x3F);
    }
    if (s.size() == 3) {
        return ((b(0) & 0x0F) << 12) | ((b(1) & 0x3F) << 6) | (b(2) & 0x3F);
    }
    return ((b(0) & 0x07) << 18) | ((b(1) & 0x3F) << 12) | ((b(2) & 0x3F) << 6) | (b(3) & 0x3F);
}

bool isWideCodePoint(char32_t cp) {
    if (cp < 0x1100) {
        return false; // fast path: ASCII and Latin/Greek/Cyrillic/Hebrew/Arabic are not wide
    }
    const auto it = std::upper_bound(std::begin(kWide), std::end(kWide), cp,
                                     [](char32_t c, const Range& r) { return c < r.lo; });
    return it != std::begin(kWide) && cp <= std::prev(it)->hi;
}

